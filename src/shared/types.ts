// Where an asset comes from in the game, so a map can be rebuilt from the game's own files.
export type AssetSource =
  // a whole model, as the game places it (bin/field/model/buildmodel/<name>.gfbmdl inside buildmodel.gfpak)
  | { kind: 'model'; pak: string; path: string | null; fileIndex: number }
  // one instance cut out of a zone model: the meshes of a group, the triangles of one cluster, moved to the origin
  | { kind: 'zonePiece'; pak: string; fileIndex: number; family: string; pivot: [number, number, number]; instance: number }
  // a whole zone model, in its own coordinates
  | { kind: 'zone'; pak: string; fileIndex: number }
  // a ground tile generated by the editor with a game texture
  | { kind: 'tile'; texture: string; cells: number }
  // the editor's own markers: where the player arrives, where the teleporter back is
  | { kind: 'marker'; marker: 'spawn' | 'exit' | 'grass' | 'terrain' | 'stairs' | 'sign' };

export interface AssetEntry {
  id: string;
  name: string;
  category: Category;
  zone: string | null; // zone it was cut from
  source: AssetSource;
  bounds: [number, number, number, number, number, number];
  triangles: number;
}

export interface Catalog {
  version: number;
  gamePath: string;
  createdAt: string;
  assets: AssetEntry[];
}

export const CATALOG_VERSION = 6;

// ---- map file (.lgmap, JSON)

export interface MapObject {
  id: string;
  name: string;
  asset: string | null; // asset id; null for a group (folder) node
  parent: string | null;
  position: [number, number, number]; // game units (1 cell = 100), Y up, relative to parent
  rotation: [number, number, number]; // degrees, XYZ
  scale: [number, number, number];
  visible: boolean;
  locked: boolean;
  props?: Record<string, string | number | boolean>;
  // a tall-grass zone (asset lg.grass): its size in cells and the wild Pokémon that appear in it
  grass?: GrassZone;
  terrain?: TerrainBlock; // asset lg.terrain
  stairs?: StairsBlock; // asset lg.stairs
  sign?: { text: string }; // asset lg.sign: what the player reads with A
}

export interface WildSlot {
  species: number; // national Pokédex number (1-151, 808 Meltan, 809 Melmetal)
  rate: number; // percent; the slots of a table add up to 100
}

export interface WildTable {
  minLevel: number;
  maxLevel: number;
  slots: WildSlot[]; // up to 10
}

export interface GrassZone {
  w: number; // cells along X
  d: number; // cells along Z
  wild: WildTable; // Let's Go Pikachu and Eevee alike
}

export const GRASS_ASSET = 'lg.grass';

// the cells a grass zone covers: x/z of its center measured from the grid's origin (the editor and the export agree)
export function grassRect(x: number, z: number, g: GrassZone, cell: number): { cx0: number; cz0: number; w: number; d: number } {
  const w = Math.max(1, Math.round(g.w));
  const d = Math.max(1, Math.round(g.d));
  return { cx0: Math.floor(x / cell - w / 2 + 0.5), cz0: Math.floor(z / cell - d / 2 + 0.5), w, d };
}

export function defaultGrass(): GrassZone {
  return {
    w: 4,
    d: 3,
    wild: { minLevel: 3, maxLevel: 5, slots: [{ species: 16, rate: 40 }, { species: 19, rate: 30 }, { species: 10, rate: 30 }] },
  };
}

