export type EdgeKind = 'wall' | 'ledge'; // a cliff that blocks / a ledge the player jumps down from
export type Side = 'n' | 'e' | 's' | 'w'; // n = -Z (up on the screen in the game), e = +X

// a block of raised ground: a rectangle of cells, from the object's height up to `height` above it
export interface TerrainBlock {
  w: number; // cells along X
  d: number; // cells along Z
  height: number; // game units (a ledge in the game is 50 high)
  top: string; // texture of the top (a ground texture)
  side: string; // texture of the sides
  edges: Record<Side, EdgeKind>;
}

// stairs: `w` cells wide and `length` cells long, climbing `height` from the object's height in the direction the
// object faces (rotation Y 0: towards -Z, 90: -X, 180: +Z, 270: +X)
export interface StairsBlock {
  w: number;
  length: number;
  height: number;
  texture: string;
}

export function defaultTerrain(): TerrainBlock {
  return { w: 4, d: 3, height: 50, top: 'grass01_com', side: 'cliff04_com', edges: { n: 'wall', e: 'wall', s: 'ledge', w: 'wall' } };
}

export function defaultStairs(): StairsBlock {
  return { w: 1, length: 2, height: 50, texture: 'stairs01_03_area04' };
}

// the cells a rectangle centered at (x, z) covers (measured from the grid's origin): as grass zones
export function cellRect(x: number, z: number, w: number, d: number, cell: number): { cx0: number; cz0: number; w: number; d: number } {
  return grassRect(x, z, { w, d, wild: { minLevel: 1, maxLevel: 1, slots: [] } }, cell);
}

export interface MapGrid {
  cellSize: number; // game units per cell (the game's tile: 100)
  width: number; // cells
  depth: number;
  originX: number; // world position of cell (0,0)'s corner
  originZ: number;
}

export interface MapDocument {
  format: 'letsgo-map';
  version: 1;
  name: string;
  author: string;
  description: string;
  grid: MapGrid;
  // the export keeps the map slot's own ground (a test meadow) under the map: true / false; unset: only when the map
  // has no ground tiles of its own
  slotGround?: boolean;
  // a ring of ground around the grid in the game (only drawn: beyond the map's edges the game shows its background)
  border?: { texture: string; cells: number } | null;
  objects: MapObject[];
  // asset id -> where it comes from in the game files (copied from the catalog when saving, so the map stands alone)
  assets: Record<string, { name: string; category: Category; source: AssetSource }>;
}

export function emptyMap(): MapDocument {
  return {
    format: 'letsgo-map',
    version: 1,
    name: 'Nuevo mapa',
    author: '',
    description: '',
    grid: { cellSize: 100, width: 32, depth: 32, originX: -1600, originZ: -1600 },
    objects: [],
    assets: {},
  };
}

